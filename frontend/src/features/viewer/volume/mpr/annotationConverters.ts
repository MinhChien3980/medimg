/**
 * Conversion between our volume annotations (API: LPS mm points + view plane) and Cornerstone3D
 * 5.x annotations of `RectangleROITool`, `EllipticalROITool` and `LengthTool` (pure, unit tested;
 * no Cornerstone import, so it runs in jsdom).
 *
 * Both sides use the same world space: Cornerstone3D derives LPS millimetres from the NIfTI affine,
 * the space of the meshes and centroids. Handle order is Cornerstone's and is kept verbatim:
 * rectangle = 4 corners (top-left, top-right, bottom-left, bottom-right on the view), ellipse =
 * ends of its axes (bottom, top, left, right), length = 2 ends. An annotation is shown on the
 * views whose plane normal is parallel to `viewPlaneNormal`, on the slice through `points[0]`.
 */
import type { Measurement, Vec3, VolumeAnnotationKind, VolumeGeometry } from '@/api/types';

export const TOOL_NAMES: Record<VolumeAnnotationKind, string> = {
  RECTANGLE_ROI: 'RectangleROI',
  ELLIPSE_ROI: 'EllipticalROI',
  LENGTH: 'Length',
};

const POINT_COUNT: Record<VolumeAnnotationKind, number> = {
  RECTANGLE_ROI: 4,
  ELLIPSE_ROI: 4,
  LENGTH: 2,
};

export function kindOfTool(toolName: string | undefined): VolumeAnnotationKind | null {
  const entry = Object.entries(TOOL_NAMES).find(([, name]) => name === toolName);
  return entry ? (entry[0] as VolumeAnnotationKind) : null;
}

/** The subset of a Cornerstone3D annotation these tools read and write. */
export interface CsAnnotation {
  annotationUID?: string;
  highlighted?: boolean;
  invalidated?: boolean;
  isLocked?: boolean;
  isVisible?: boolean;
  autoGenerated?: boolean;
  metadata: {
    toolName: string;
    FrameOfReferenceUID?: string;
    viewPlaneNormal?: number[];
    viewUp?: number[];
    sliceIndex?: number;
    referencedImageId?: string;
    [key: string]: unknown;
  };
  data: {
    handles: {
      points: number[][];
      activeHandleIndex?: number | null;
      textBox?: unknown;
      [key: string]: unknown;
    };
    label?: string;
    cachedStats?: Record<string, Record<string, unknown> | undefined>;
    [key: string]: unknown;
  };
}

/** What the viewer shows for one stored annotation. */
export interface MprAnnotationInput {
  uid: string;
  kind: VolumeAnnotationKind;
  geometry: VolumeGeometry;
  label: string | null;
  /** Someone else's annotation: displayed, not editable. */
  locked: boolean;
}

function isVec3(value: unknown): value is Vec3 {
  return (
    Array.isArray(value) &&
    value.length === 3 &&
    value.every((v) => typeof v === 'number' && Number.isFinite(v))
  );
}

function vec3(value: readonly number[]): Vec3 {
  return [value[0] ?? 0, value[1] ?? 0, value[2] ?? 0];
}

/** Our geometry, or null when it does not fit the kind (wrong point count, non-finite numbers). */
export function parseVolumeGeometry(
  kind: VolumeAnnotationKind,
  geometry: unknown,
): VolumeGeometry | null {
  if (typeof geometry !== 'object' || geometry === null) return null;
  const g = geometry as Record<string, unknown>;
  const points = g.points;
  if (!Array.isArray(points) || points.length !== POINT_COUNT[kind] || !points.every(isVec3)) {
    return null;
  }
  if (!isVec3(g.viewPlaneNormal) || !isVec3(g.viewUp)) return null;
  // The server rejects unknown fields and needs no null: the slice index is sent only when known.
  return {
    points: points.map((p) => vec3(p)),
    viewPlaneNormal: vec3(g.viewPlaneNormal),
    viewUp: vec3(g.viewUp),
    ...(typeof g.sliceIndex === 'number' ? { sliceIndex: g.sliceIndex } : {}),
  };
}

/**
 * A Cornerstone annotation for a stored one, ready for `annotation.state.addAnnotation`. Its
 * statistics are left empty and flagged invalid, so the tool computes them on first render.
 */
export function toCornerstoneAnnotation(
  input: MprAnnotationInput,
  frameOfReferenceUID: string,
): CsAnnotation {
  const { geometry } = input;
  return {
    annotationUID: input.uid,
    highlighted: false,
    invalidated: true,
    isLocked: input.locked,
    isVisible: true,
    autoGenerated: false,
    metadata: {
      toolName: TOOL_NAMES[input.kind],
      FrameOfReferenceUID: frameOfReferenceUID,
      viewPlaneNormal: [...geometry.viewPlaneNormal],
      viewUp: [...geometry.viewUp],
      ...(geometry.sliceIndex != null ? { sliceIndex: geometry.sliceIndex } : {}),
    },
    data: {
      handles: {
        points: geometry.points.map((p) => [...p]),
        activeHandleIndex: null,
        textBox: {
          hasMoved: false,
          worldPosition: [0, 0, 0],
          worldBoundingBox: {
            topLeft: [0, 0, 0],
            topRight: [0, 0, 0],
            bottomLeft: [0, 0, 0],
            bottomRight: [0, 0, 0],
          },
        },
      },
      label: input.label ?? '',
      cachedStats: {},
    },
  };
}

function round(value: number, digits: number): number {
  const f = 10 ** digits;
  return Math.round(value * f) / f;
}

function finite(value: unknown): value is number {
  return typeof value === 'number' && Number.isFinite(value);
}

/**
 * Measurement from the tool's cached statistics (first measured target): length in mm, area in
 * mm², and the mean / standard deviation of the voxels inside an ROI in HU, for a CT only (other
 * volumes are not in Hounsfield units). Values in pixels (no calibration) are not reported.
 */
export function measurementFromStats(
  kind: VolumeAnnotationKind,
  cachedStats: CsAnnotation['data']['cachedStats'],
  hounsfield: boolean,
): Measurement | null {
  const stats = Object.values(cachedStats ?? {}).find((s) => s && Object.keys(s).length > 0);
  if (!stats) return null;
  const m: Measurement = {};
  if (kind === 'LENGTH') {
    const unit = typeof stats.unit === 'string' ? stats.unit : '';
    if (finite(stats.length) && stats.length > 0 && unit.startsWith('mm')) {
      m.lengthMm = round(stats.length, 2);
    }
  } else {
    const areaUnit = typeof stats.areaUnit === 'string' ? stats.areaUnit : '';
    if (finite(stats.area) && stats.area > 0 && areaUnit.startsWith('mm')) {
      m.areaMm2 = round(stats.area, 2);
    }
    if (hounsfield && finite(stats.mean)) m.meanHu = round(stats.mean, 1);
    if (hounsfield && finite(stats.stdDev) && stats.stdDev >= 0) m.stdHu = round(stats.stdDev, 1);
  }
  return Object.keys(m).length > 0 ? m : null;
}

/** True once an ROI's statistics have been computed (a length needs none beyond its length). */
export function hasStats(annotation: CsAnnotation): boolean {
  const stats = Object.values(annotation.data.cachedStats ?? {}).find(
    (s) => s && Object.keys(s).length > 0,
  );
  if (!stats) return false;
  return kindOfTool(annotation.metadata.toolName) === 'LENGTH'
    ? finite(stats.length)
    : finite(stats.area);
}

export interface ConvertedAnnotation {
  kind: VolumeAnnotationKind;
  geometry: VolumeGeometry;
  measurement: Measurement | null;
}

/**
 * Our annotation for a Cornerstone one drawn or edited by the user; null for other tools or a
 * malformed annotation. `fallback` supplies the view plane when the annotation's metadata lacks it
 * (the camera of the view it was drawn on).
 */
export function fromCornerstoneAnnotation(
  annotation: CsAnnotation,
  options: { hounsfield: boolean; fallback?: { viewPlaneNormal: Vec3; viewUp: Vec3 } },
): ConvertedAnnotation | null {
  const kind = kindOfTool(annotation.metadata.toolName);
  if (!kind) return null;
  const normal = annotation.metadata.viewPlaneNormal ?? options.fallback?.viewPlaneNormal;
  const up = annotation.metadata.viewUp ?? options.fallback?.viewUp;
  const geometry = parseVolumeGeometry(kind, {
    points: annotation.data.handles.points.map((p) => [...p]),
    viewPlaneNormal: normal ? [...normal] : null,
    viewUp: up ? [...up] : null,
    sliceIndex: annotation.metadata.sliceIndex,
  });
  if (!geometry) return null;
  return {
    kind,
    geometry: {
      ...geometry,
      points: geometry.points.map((p) => p.map((v) => round(v, 3)) as Vec3),
    },
    measurement: measurementFromStats(kind, annotation.data.cachedStats, options.hounsfield),
  };
}

/** Centre of the annotation's points: where the crosshair goes to show it. */
export function annotationCenter(geometry: Pick<VolumeGeometry, 'points'>): Vec3 {
  const n = geometry.points.length || 1;
  const sum = geometry.points.reduce<Vec3>(
    (acc, p) => [acc[0] + p[0], acc[1] + p[1], acc[2] + p[2]],
    [0, 0, 0],
  );
  return [sum[0] / n, sum[1] / n, sum[2] / n];
}

/** Stable key of what is displayed for an annotation (to skip re-adding unchanged ones). */
export function displayKey(input: MprAnnotationInput): string {
  return JSON.stringify([input.kind, input.geometry.points, input.geometry.viewPlaneNormal]);
}
